    public void tampilData(){

        model = new DefaultTableModel();

        model.addColumn("ID");
        model.addColumn("Tanggal");
        model.addColumn("Nama");
        model.addColumn("BB");
        model.addColumn("TB");
        model.addColumn("Usia");
        model.addColumn("JK");
        model.addColumn("Status");

        tblTampil.setModel(model);

        try{

            String sql=
            "SELECT kegiatan.id_kegiatan, kegiatan.tanggal, balita.nama, kegiatan.berat_badan, kegiatan.tinggi_badan, kegiatan.usia, kegiatan.jenis_kelamin, kegiatan.status_gizi FROM kegiatan INNER JOIN balita ON kegiatan.id_balita=balita.id_balita";

            PreparedStatement ps=conn.prepareStatement(sql);

            ResultSet rs=ps.executeQuery();

            while(rs.next()){

                model.addRow(new Object[]{

                    rs.getInt(1),
                    rs.getString(2),
                    rs.getString(3),
                    rs.getDouble(4),
                    rs.getDouble(5),
                    rs.getInt(6),
                    rs.getString(7),
                    rs.getString(8)

                });

            }

        }catch(Exception e){

            JOptionPane.showMessageDialog(null,e.getMessage());

        }

    }
    
    public String hitungUsia(String tgl){

        java.time.LocalDate lahir=java.time.LocalDate.parse(tgl);

        java.time.Period p=java.time.Period.between(lahir, java.time.LocalDate.now());

        return String.valueOf(p.getYears()*12+p.getMonths());
    }
    
    

