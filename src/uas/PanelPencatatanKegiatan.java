    private void btnCariActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCariActionPerformed
        try{

            String sql = "SELECT * FROM balita WHERE nik=?";
            PreparedStatement ps = conn.prepareStatement(sql);
            ps.setString(1, txtCariNik.getText());

            ResultSet rs = ps.executeQuery();

            if(rs.next()){

                idBalita = rs.getInt("id_balita");

                txtNamaBalita.setText(rs.getString("nama"));
                txtJenisKelamin.setText(rs.getString("jenis_kelamin"));
                txtUsia.setText(hitungUsia(rs.getString("tgl_lahir")));

            }else{

                JOptionPane.showMessageDialog(null,"Data tidak ditemukan");

            }

        }catch(Exception e){

            JOptionPane.showMessageDialog(null,e.getMessage());

        }
// TODO add your handling code here:
    }//GEN-LAST:event_btnCariActionPerformed

    private void btnSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanActionPerformed
        try{

            String sql = "INSERT INTO kegiatan(tanggal,id_balita,nama_balita,berat_badan,tinggi_badan,usia,jenis_kelamin,status_gizi) VALUES(?,?,?,?,?,?,?,?)";

            PreparedStatement ps=conn.prepareStatement(sql);

            ps.setString(1, txtTanggal.getText());
            ps.setInt(2, idBalita);
            ps.setString(3, txtNamaBalita.getText());
            ps.setDouble(4, Double.parseDouble(txtBB.getText()));
            ps.setDouble(5, Double.parseDouble(txtTB.getText()));
            ps.setInt(6, Integer.parseInt(txtUsia.getText()));
            ps.setString(7, txtJenisKelamin.getText());
            ps.setString(8, txtStatusGizi.getText());

            ps.executeUpdate();

            JOptionPane.showMessageDialog(null,"Data berhasil disimpan");

            tampilData();

        }catch(Exception e){

            JOptionPane.showMessageDialog(null,e.getMessage());

        }
// TODO add your handling code here:
    }//GEN-LAST:event_btnSimpanActionPerformed

    private void btnHitungActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHitungActionPerformed
        double bb=Double.parseDouble(txtBB.getText());

        if(bb<10){
            txtStatusGizi.setText("Kurang");
        }else if(bb<18){
            txtStatusGizi.setText("Normal");
        }else{
            txtStatusGizi.setText("Lebih");
        }// TODO add your handling code here:
    }//GEN-LAST:event_btnHitungActionPerformed


