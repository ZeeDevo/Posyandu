    private void btnTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahActionPerformed
        try{

            String sql="INSERT INTO ibu_hamil(nik,nama,hpht,usia_kehamilan,risiko,alamat) VALUES(?,?,?,?,?,?)";

            PreparedStatement ps=conn.prepareStatement(sql);

            ps.setString(1, txtNik.getText());
            ps.setString(2, txtNama.getText());
            ps.setString(3, txtHPHT.getText());
            ps.setInt(4, Integer.parseInt(txtUsiaKehamilan.getText()));
            ps.setString(5, txtRisiko.getText());
            ps.setString(6, txtAlamat.getText());

            ps.executeUpdate();

            JOptionPane.showMessageDialog(null,"Data berhasil ditambahkan");

            kosongkanForm();
            tampilData();

        }catch(Exception e){

            JOptionPane.showMessageDialog(null,e.getMessage());

        }// TODO add your handling code here:
    }//GEN-LAST:event_btnTambahActionPerformed

