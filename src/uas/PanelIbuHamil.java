        model.addColumn("ID");
        model.addColumn("NIK");
        model.addColumn("Nama");
        model.addColumn("HPHT");
        model.addColumn("Usia Kehamilan");
        model.addColumn("Risiko");
        model.addColumn("Alamat");

        tblIbuHamil.setModel(model);

