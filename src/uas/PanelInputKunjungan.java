    public void tampilData(){

        model = new DefaultTableModel();

        model.addColumn("ID");
        model.addColumn("Tanggal");
        model.addColumn("NIK");
        model.addColumn("Nama");
        model.addColumn("Tanggal Lahir");
        model.addColumn("Nama Ortu");
        model.addColumn("Alamat");
        model.addColumn("Jenis Pasien");

        tblBalita.setModel(model);

        try{

            String sql="SELECT * FROM kunjungan";

            PreparedStatement ps=conn.prepareStatement(sql);

            ResultSet rs=ps.executeQuery();

            while(rs.next()){

                model.addRow(new Object[]{

                    rs.getInt("id_kunjungan"),
                    rs.getDate("tanggal_kunjungan"),
                    rs.getString("nik"),
                    rs.getString("nama"),
                    rs.getDate("tanggal_lahir"),
                    rs.getString("nama_ortu"),
                    rs.getString("alamat"),
                    rs.getString("jenis_pasien")

                });

            }

        }catch(Exception e){

            JOptionPane.showMessageDialog(null,e.getMessage());

        }

    }
    
