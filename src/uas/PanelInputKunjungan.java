    private void btnTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahActionPerformed
        try{
            String sql="INSERT INTO kunjungan(tanggal_kunjungan,nik,nama,tanggal_lahir,nama_ortu,alamat,jenis_pasien) VALUES(?,?,?,?,?,?,?)";

            PreparedStatement ps=conn.prepareStatement(sql);

            ps.setString(1, txtTanggalKunjungan.getText());
            ps.setString(2, txtNik.getText());
            ps.setString(3, txtNama.getText());
            ps.setString(4, txtTanggalLahir.getText());
            ps.setString(5, txtNamaOrtu.getText());
            ps.setString(6, txtAlamat.getText());

            ps.setString(7, cmbJenisPasien.getSelectedItem().toString());

            ps.executeUpdate();

            JOptionPane.showMessageDialog(null,"Data berhasil disimpan");

            kosongkanForm();
            tampilData();

        }catch(Exception e){

            JOptionPane.showMessageDialog(null,e.getMessage());

        }// TODO add your handling code here:
    }//GEN-LAST:event_btnTambahActionPerformed

    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
            try{

            String sql="UPDATE kunjungan SET tanggal_kunjungan=?,nama=?,tanggal_lahir=?,nama_ortu=?,alamat=?,jenis_pasien=? WHERE nik=?";

            PreparedStatement ps=conn.prepareStatement(sql);

            ps.setString(1, txtTanggalKunjungan.getText());
            ps.setString(2, txtNama.getText());
            ps.setString(3, txtTanggalLahir.getText());
            ps.setString(4, txtNamaOrtu.getText());
            ps.setString(5, txtAlamat.getText());
            ps.setString(6, txtAlamat.getText());
            ps.setString(7, cmbJenisPasien.getSelectedItem().toString());
            ps.setString(8, txtNik.getText());

            ps.executeUpdate();

            JOptionPane.showMessageDialog(null,"Data berhasil diubah");

            kosongkanForm();
            tampilData();

        }catch(Exception e){

            JOptionPane.showMessageDialog(null,e.getMessage());

        }// TODO add your handling code here:
    }//GEN-LAST:event_btnEditActionPerformed

    private void btnHapusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnHapusActionPerformed
        int jawab=JOptionPane.showConfirmDialog(
            null,
            "Yakin ingin menghapus?",
            "Konfirmasi",
            JOptionPane.YES_NO_OPTION);

        if(jawab==JOptionPane.YES_OPTION){

            try{

                String sql="DELETE FROM kunjungan WHERE nik=?";

                PreparedStatement ps=conn.prepareStatement(sql);

                ps.setString(1, txtNik.getText());

                ps.executeUpdate();

                JOptionPane.showMessageDialog(null,"Data berhasil dihapus");

                kosongkanForm();
                tampilData();

            }catch(Exception e){

                JOptionPane.showMessageDialog(null,e.getMessage());

            }

        }// TODO add your handling code here:
    }//GEN-LAST:event_btnHapusActionPerformed

